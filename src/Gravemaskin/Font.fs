/// A 5x7 bitmap font, written out by hand and baked into an 8x8-cell atlas at
/// startup. It is the only "asset" in the game and it is 50 lines of source.
[<RequireQualifiedAccess>]
module Font =
    [<Literal>]
    let CellSize = 8

    [<Literal>]
    let Columns = 16

    [<Literal>]
    let Rows = 6

    let AtlasWidth = CellSize * Columns
    let AtlasHeight = CellSize * Rows

    /// Rows of 5 pixels, top to bottom, '#' set. Only the glyphs the HUD
