    /// Character -> cell index in the atlas. Space and unknown glyphs map to a
    /// blank cell (index 0 is left empty on purpose).
    let private cellOf =
        let map = Dictionary<char, int>()
        glyphs |> List.iteri (fun i (ch, _) -> map.[ch] <- i + 1)
        map

    let cellIndex (ch: char) =
        let upper = Char.ToUpperInvariant ch
        match cellOf.TryGetValue upper with
        | true, index -> index
        | _ -> 0

    /// Rasterizes the atlas into a single-channel byte buffer. Glyphs sit in
    /// the top-left 5x7 of each 8x8 cell, leaving natural spacing.
    let buildAtlas () : byte array =
        let pixels = Array.zeroCreate<byte> (AtlasWidth * AtlasHeight)
        glyphs
        |> List.iteri (fun i (_, pattern) ->
            let cell = i + 1
            let cellX = (cell % Columns) * CellSize
            let cellY = (cell / Columns) * CellSize
            pattern.Split '/'
            |> Array.iteri (fun row line ->
                line |> Seq.iteri (fun col ch ->
                    if ch = '#' then
                        let x = cellX + col
                        let y = cellY + row
                        if x < AtlasWidth && y < AtlasHeight then pixels.[y * AtlasWidth + x] <- 255uy)))
        pixels
